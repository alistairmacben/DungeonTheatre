// Builds the spell icon map, once, at dev time.
//
// Matching 318 spell names against 396 icon filenames is fuzzy work — British
// spellings, apostrophes, MediaWiki's duplicate " (1)" markers and doubled
// ".png.webp" extensions — and none of that belongs in the browser on every
// render. So it happens here and the answer is committed as a plain lookup.
//
// Reads `game icons/`, which is deliberately NOT in the repo (25MB of bg3.wiki
// assets, see .gitignore). Re-running this needs that folder; the generated
// output and the copied icons are what the app actually ships.
//
//   node player/scripts/generate-spell-icons.mjs
//
// Roughly half the SRD spell list has bespoke art. The rest is not a gap the
// UI has to apologise for: `spellIcon()` returns undefined and the caller
// falls back to a generic glyph keyed on the spell's damage type or school,
// so every spell shows something.

import { copyFileSync, mkdirSync, readdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { loadContent } from '../../test/bundle/engine.mjs'

const ROOT = join(import.meta.dirname, '..', '..')
const SPELL_DIR = join(ROOT, 'game icons', '2 Category_Spell icons - bg3.wiki')
const GENERIC_DIR = join(ROOT, 'game icons', '1 Category_Generic icons - bg3.wiki')
const OUT_SPELLS = join(ROOT, 'player', 'public', 'icons', 'spells')
const OUT_GENERIC = join(ROOT, 'player', 'public', 'icons', 'generic')
const OUT_TS = join(ROOT, 'player', 'src', 'ui', 'spellIcons.generated.ts')

/** Both sides reduced to a comparable letters-and-digits key. */
function norm(s) {
  return decodeURIComponent(s)
    .toLowerCase()
    .replace(/’/g, "'")
    .replace(/armour/g, 'armor')
    .replace(/[^a-z0-9]/g, '')
}

function iconKey(file) {
  // Order matters: the duplicate marker " (1)" sits BEFORE the extension, so
  // it has to go before any attempt to strip a trailing _Unfaded_Icon.
  let s = file.replace(/^\d+px-/, '')
  s = s.replace(/\.(png|webp)$/i, '')
  s = s.replace(/\.png$/i, '')
  s = s.replace(/\s*\(\d+\)$/, '')
  s = s.replace(/_Unfaded_Icon$/i, '')
  s = s.replace(/_Icon$/i, '')
  s = s.replace(/_Spell$/i, '')
  return norm(s)
}

/** `srd:spell.fire-bolt` -> `fire-bolt`. The lookup key the app uses. */
const idSuffix = (id) => id.slice(id.lastIndexOf('.') + 1)

// Windows refuses to open a path component named for a DOS device, whatever
// the extension — a file called `con.webp` is unopenable and ungittable.
const RESERVED = /^(con|prn|aux|nul|com[1-9]|lpt[1-9])$/i

function pickBest(a, b) {
  if (!a) return b
  // Prefer a native file over a MediaWiki thumbnail, then the shorter name.
  const aThumb = /^\d+px-/.test(a)
  const bThumb = /^\d+px-/.test(b)
  if (aThumb !== bThumb) return aThumb ? b : a
  return b.length < a.length ? b : a
}

const files = readdirSync(SPELL_DIR).filter((f) => /\.(png|webp)$/i.test(f))
const byKey = new Map()
for (const f of files) {
  const k = iconKey(f)
  byKey.set(k, pickBest(byKey.get(k), f))
}

mkdirSync(OUT_SPELLS, { recursive: true })
mkdirSync(OUT_GENERIC, { recursive: true })

const content = loadContent()
const entries = []
const misses = []
for (const spell of [...content.spells.values()].sort((a, b) => a.id.localeCompare(b.id))) {
  const source = byKey.get(norm(spell.name))
  const key = idSuffix(spell.id)
  if (!source || RESERVED.test(key)) {
    misses.push(spell)
    continue
  }
  const ext = /\.webp$/i.test(source) ? 'webp' : 'png'
  copyFileSync(join(SPELL_DIR, source), join(OUT_SPELLS, `${key}.${ext}`))
  entries.push([key, `${key}.${ext}`])
}

// The fallback set, copied wholesale — it is 33 small files and every one is
// reachable through either a damage type or a school.
const generics = []
for (const f of readdirSync(GENERIC_DIR).filter((f) => /\.(png|webp)$/i.test(f))) {
  const key = norm(f.replace(/^Generic_/, '').replace(/_Unfaded_Icon.*$/, ''))
  if (!key || RESERVED.test(key)) continue
  const ext = /\.webp$/i.test(f) ? 'webp' : 'png'
  copyFileSync(join(GENERIC_DIR, f), join(OUT_GENERIC, `${key}.${ext}`))
  generics.push([key, `${key}.${ext}`])
}
generics.sort((a, b) => a[0].localeCompare(b[0]))

const pct = Math.round((entries.length / content.spells.size) * 100)
writeFileSync(OUT_TS, `// GENERATED by player/scripts/generate-spell-icons.mjs — do not edit by hand.
//
// ${entries.length} of ${content.spells.size} SRD spells (${pct}%) have bespoke art in the
// bg3.wiki set. The remainder are genuinely absent from it — BG3 implements
// almost nothing above 6th level — so callers fall back to a generic glyph
// rather than treating a miss as an error.

export const SPELL_ICONS: Record<string, string> = {
${entries.map(([k, f]) => `  '${k}': '/icons/spells/${f}'`).join(',\n')}
}

/** Damage types and schools, for the fallback when a spell has no art. */
export const GENERIC_ICONS: Record<string, string> = {
${generics.map(([k, f]) => `  '${k}': '/icons/generic/${f}'`).join(',\n')}
}
`)

console.log(`spells matched : ${entries.length}/${content.spells.size} (${pct}%)`)
console.log(`generic glyphs : ${generics.length}`)
console.log(`unmatched      : ${misses.length} (fall back to school/damage glyph)`)
