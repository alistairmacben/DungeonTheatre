// Picks representative icons for equipment categories and universal actions.
//
// Matching SRD magic items to bg3.wiki art by name does not work: 37 of 323
// items (11%) hit, because BG3 ships its own itemisation — "Hag's Ring",
// "Crusher's Ring" — rather than the SRD's generic magic items.
//
// So equipment is iconified by CATEGORY: every ring shows a ring, every cloak
// a cloak. That reads correctly at a glance and covers 100% of items.
//
//   node player/scripts/generate-item-icons.mjs

import { copyFileSync, mkdirSync, readdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const ROOT = join(import.meta.dirname, '..', '..')
const ICONS = join(ROOT, 'game icons')
const OUT_DIR = join(ROOT, 'player', 'public', 'icons', 'categories')
const OUT_ACTIONS = join(ROOT, 'player', 'public', 'icons', 'actions')

/**
 * Slot (or pseudo-slot) -> folder, and the file to take from it.
 *
 * `prefer` is named explicitly because the shortest-name rule alone picks
 * badly: left to itself it chose "Broken_Shield" for shields, a dog collar for
 * amulets and a signed trade visa for scrolls. The rule remains the fallback,
 * so a missing preferred file degrades to a plausible pick rather than nothing.
 */
const CATEGORIES = {
  armor: { dir: 'Category_Medium armour icons - bg3.wiki', prefer: 'Breastplate_Unfaded_Icon.png' },
  shield: { dir: 'Category_Shield icons - bg3.wiki', prefer: 'Item_WPN_HUM_Shield_C_1_Unfaded_Icon.png' },
  head: { dir: 'Category_Helmet icons - bg3.wiki', prefer: 'Leather_Helmet_Unfaded_Icon.png' },
  cloak: { dir: 'Category_Cloak icons - bg3.wiki', prefer: 'Cloak_Unfaded_Icon.png' },
  gloves: { dir: 'Category_Gloves icons - bg3.wiki', prefer: 'Gloves_Leather_Unfaded_Icon.png' },
  boots: { dir: 'Category_Boots icons - bg3.wiki', prefer: 'Boots_Leather_Unfaded_Icon.png' },
  amulet: { dir: 'Category_Amulet icons - bg3.wiki', prefer: 'Amulet_Necklace_A_Bronze_A_Unfaded_Icon.png' },
  ring: { dir: 'Category_Ring icons - bg3.wiki', prefer: 'Gemless_Ring_Unfaded_Icon.png' },
  potion: { dir: '1 Category_Potion icons - bg3.wiki', prefer: 'POT_Potion_of_Healing_Unfaded_Icon.png' },
  scroll: { dir: 'Category_Scroll icons - bg3.wiki', prefer: 'Scroll_of_Aid_Unfaded_Icon.png' },
  wand: { dir: 'Category_Wand icons - bg3.wiki', prefer: 'Item_WPN_HUM_Wand_A_0_Unfaded_Icon.png' },
  instrument: { dir: 'Category_Instrument icons - bg3.wiki', prefer: 'Instrument_Horn_Unfaded_Icon.png' }
}

/**
 * The universal actions every character has.
 *
 * Dodge is deliberately absent: BG3 does not implement it as an action, so
 * there is no art for it and it resolves to a generic glyph at lookup time.
 */
const ACTION_DIR = 'Category_Action icons - bg3.wiki'
const ACTIONS = {
  dash: 'Dash_Unfaded_Icon.webp',
  disengage: 'Disengage_Unfaded_Icon.webp',
  hide: 'Hide_Unfaded_Icon.webp',
  help: 'Help_Unfaded_Icon.webp',
  jump: 'Jump_Unfaded_Icon.webp',
  shove: 'Shove_Unfaded_Icon.webp'
}

// A named, one-off item rather than a plain example of its kind.
const UNIQUE = /(_of_|_the_|plusone|plustwo|plusthree|'s_)/i

function representative(dir, prefer) {
  let files
  try { files = readdirSync(join(ICONS, dir)) } catch { return undefined }
  if (prefer && files.includes(prefer)) return prefer
  const images = files.filter((f) => /\.(png|webp)$/i.test(f))
  const plain = images.filter((f) => !/^\d+px-/.test(f)).filter((f) => !UNIQUE.test(f))
  const pool = plain.length > 0 ? plain : images
  // Shortest name wins, ties alphabetical, so the result is stable.
  return pool.sort((a, b) => a.length - b.length || a.localeCompare(b))[0]
}

function emit(path, banner, entries, urlBase, constName) {
  writeFileSync(path, `// GENERATED by player/scripts/generate-item-icons.mjs — do not edit by hand.
//
${banner}

export const ${constName}: Record<string, string> = {
${entries.map(([k, f]) => `  '${k}': '${urlBase}/${f}'`).join(',\n')}
}
`)
}

mkdirSync(OUT_DIR, { recursive: true })
const picked = []
for (const [key, { dir, prefer }] of Object.entries(CATEGORIES)) {
  const file = representative(dir, prefer)
  if (!file) { console.warn(`no icon found for ${key} (${dir})`); continue }
  const ext = /\.webp$/i.test(file) ? 'webp' : 'png'
  copyFileSync(join(ICONS, dir, file), join(OUT_DIR, `${key}.${ext}`))
  picked.push([key, `${key}.${ext}`, file, prefer === file ? '' : ' (fallback)'])
}

mkdirSync(OUT_ACTIONS, { recursive: true })
const actions = []
for (const [key, file] of Object.entries(ACTIONS)) {
  try {
    copyFileSync(join(ICONS, ACTION_DIR, file), join(OUT_ACTIONS, `${key}.webp`))
    actions.push([key, `${key}.webp`])
  } catch {
    console.warn(`missing action icon: ${file}`)
  }
}

emit(
  join(ROOT, 'player', 'src', 'ui', 'itemIcons.generated.ts'),
  '// One representative icon per equipment category. Items are iconified by\n'
  + '// what KIND of thing they are, not by name: only 11% of SRD items have\n'
  + '// matching bg3.wiki art, because BG3 ships its own itemisation.',
  picked.map(([k, f]) => [k, f]), '/icons/categories', 'CATEGORY_ICONS'
)
emit(
  join(ROOT, 'player', 'src', 'ui', 'actionIcons.generated.ts'),
  '// The universal actions. Dodge is absent on purpose: BG3 has no such\n'
  + '// action, so it resolves to a generic glyph instead.',
  actions, '/icons/actions', 'ACTION_ICONS'
)

console.log('category icons:')
for (const [key, , source, note] of picked) console.log(`  ${key.padEnd(11)} <- ${source}${note}`)
console.log(`action icons: ${actions.map(([k]) => k).join(', ')}`)
